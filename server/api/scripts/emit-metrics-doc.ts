import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { describeMetrics } from "../src/telemetry/metrics.js";

/** docs/METRICS.md: every grad_ metric grad-server exports, from the registry. */
export const OUT_PATH = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../../docs/METRICS.md",
);

const cell = (text: string): string => text.replaceAll("|", "\\|");

export const renderMetricsDoc = async (): Promise<string> => {
  const rows = (await describeMetrics()).map(
    (m) =>
      `| \`${m.name}\` | ${m.type} | ${m.labels.map((l) => `\`${l}\``).join(", ")} | ${cell(m.help)} |`,
  );

  return [
    "# grad-server metrics",
    "",
    "<!-- Generated by `pnpm -C server/api metrics:docs` from server/api/src/telemetry/metrics.ts; do not edit. -->",
    "",
    "grad-server serves these at `/metrics` in the Prometheus text format, plus the default Node.js process metrics without a prefix. Gauges sampled from Postgres are refreshed every 15 seconds and are the same on every API replica, so aggregate them with `max`, not `sum`. Labels never carry run, dataset or workspace ids; `grad_workspace_jobs` exists only with `METRICS_WORKSPACE_LABEL=true`. See [SELF_HOSTING.md](SELF_HOSTING.md#monitoring) for the dashboards, alerts and KEDA.",
    "",
    "| Metric | Type | Labels | Description |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
};

const run = async () => {
  const rendered = await renderMetricsDoc();
  if (process.argv.includes("--check")) {
    const existing = await readFile(OUT_PATH, "utf8").catch(() => "");
    if (existing !== rendered) {
      console.error(
        `${OUT_PATH} is stale. Run 'pnpm -C server/api metrics:docs'.`,
      );
      process.exit(1);
    }
    console.log("docs/METRICS.md is up to date.");
    return;
  }
  await writeFile(OUT_PATH, rendered, "utf8");
  console.log(`Wrote ${OUT_PATH}`);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) await run();
